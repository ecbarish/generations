#!/usr/bin/env node
// Writes docs/wildbond-creatures/catalog.md from the Godot game data, so the catalogue never drifts from the game.
// Run: node tools/wildbond-catalog.cjs   (no installs; reads wildbond-godot/data and scripts/figures.gd)
// --check: exit 1 if the catalogue on disk is out of date (run-all-checks can call this).
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const W = path.join(root, 'wildbond-godot');
const data = JSON.parse(fs.readFileSync(path.join(W, 'data/wildbond.json'), 'utf8'));
const evo = JSON.parse(fs.readFileSync(path.join(W, 'data/evolution.json'), 'utf8'));
const figures = fs.readFileSync(path.join(W, 'scripts/figures.gd'), 'utf8');

const S = Object.assign({}, data.SPECIES, evo.species || {});
const shapeFor = {};
for (const m of figures.matchAll(/"([a-z]+)":\s*"(serpent|turtle|moth|treefolk|fish|[a-z]+)"/g)) shapeFor[m[1]] = m[2];
const nexts = id => (evo.evos && evo.evos[id]) || (S[id].evo ? [S[id].evo] : []);

// where each creature lives in the wild (any season)
const where = {};
for (const [mid, m] of Object.entries(data.MAPS)) {
  const lists = [m.wild || []].concat(Object.values(m.seasonal || {}).map(s => s.wild || []));
  for (const l of lists) for (const [id] of l) (where[id] = where[id] || new Set()).add(m.name || mid);
}
for (const [mid, pairs] of Object.entries(evo.wild || {})) {
  const name = (data.MAPS[mid] && data.MAPS[mid].name) || mid;
  for (const [id] of pairs) (where[id] = where[id] || new Set()).add(name);
}
// lines: parent and stage
const parent = {};
for (const id of Object.keys(S)) for (const e of nexts(id)) if (S[e.to]) parent[e.to] = parent[e.to] || id;
const stage = id => (parent[id] ? stage(parent[id]) + 1 : 1);
const rootOf = id => (parent[id] ? rootOf(parent[id]) : id);
const depth = id => 1 + Math.max(0, ...nexts(id).filter(e => S[e.to]).map(e => depth(e.to)));
const bst = s => Object.values(s.base).reduce((a, b) => a + b, 0);

// the defaults the spec in docs/wildbond-creatures.md sets until a species carries its own size and tier
const SIZES = ['tiny', 'small', 'medium', 'large', 'huge'];
function size(id) {
  const s = S[id];
  if (s.size) return s.size;
  if (s.unique) return 'huge';
  const st = stage(id), n = depth(rootOf(id));
  if (n === 1) return s.big ? 'large' : 'medium';
  return SIZES[Math.min(4, (s.big ? 1 : 0) + st)];
}
function tier(id) {
  const s = S[id];
  if (s.tier) return s.tier;
  if (s.unique) return 'legend';
  const total = bst(s);
  if (depth(rootOf(id)) === 3 && total >= 530) return 'showpiece';
  return total >= 470 ? 'strong' : 'plain';
}
function line(id) {
  const r = rootOf(id);
  const walk = (k) => {
    const n = nexts(k).filter(e => S[e.to]);
    if (!n.length) return S[k].name;
    const parts = [];
    for (const e of n) {
      const child = walk(e.to);
      if (!parts.includes(child)) parts.push(child);
    }
    const at = n.map(e => e.at).filter(Boolean);
    return `${S[k].name} → ${parts.length > 1 ? '(' + parts.join(' / ') + ')' : parts[0]}${at.length === 1 ? '' : ''}`;
  };
  return depth(r) === 1 ? '(stays itself)' : walk(r);
}

const ids = Object.keys(S).sort((a, b) => {
  const ra = rootOf(a), rb = rootOf(b);
  return ra === rb ? stage(a) - stage(b) : S[ra].name.localeCompare(S[rb].name);
});
const count = (f) => ids.reduce((m, id) => ((m[f(id)] = (m[f(id)] || 0) + 1), m), {});
const fmt = (o) => Object.entries(o).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', ');
const lines = ids.filter(id => !parent[id]);
let out = `# Wildbond creature catalogue (generated)

Generated by \`node tools/wildbond-catalog.cjs\` from \`wildbond-godot/data/\`. Don't edit by hand: change the data and
run it again. The rules (sizes, tiers, world fit, how to add a creature) are in [../wildbond-creatures.md](../wildbond-creatures.md).
Size and tier show the species' own \`size\` and \`tier\` fields when it has them, otherwise the defaults that page sets (marked *).

**${ids.length} species** in ${lines.length} lines: ${lines.filter(id => depth(id) === 1).length} stay themselves, ${lines.filter(id => depth(id) === 2).length} lines of two, ${lines.filter(id => depth(id) === 3).length} lines of three.
Shapes: ${fmt(count(id => S[id].shape || shapeFor[id] || S[id].fam))}.
Elements: ${fmt(count(id => S[id].el))}.
Sizes: ${fmt(count(size))}. Tiers: ${fmt(count(tier))}.

| Creature | Shape | Element | Size | Tier | Stage | Strength | Lives in | Line |
|---|---|---|---|---|---|---|---|---|
`;
for (const id of ids) {
  const s = S[id];
  const w = where[id] ? [...where[id]].join(', ') : ((data.STARTERS || []).includes(id) ? "starter, Maren's barn" : parent[id] ? 'raised' : (s.unique ? 'one of a kind' : (s.hybrid ? 'bred at the ranch' : 'not yet placed')));
  out += `| ${s.name} | ${s.shape || shapeFor[id] || s.fam} | ${s.el} | ${size(id)}${s.size ? '' : '*'} | ${tier(id)}${s.tier ? '' : '*'} | ${stage(id)} of ${depth(rootOf(id)) + stage(rootOf(id)) - 1} | ${bst(s)} | ${w} | ${parent[id] ? '' : line(id)} |\n`;
}
const file = path.join(root, 'docs/wildbond-creatures/catalog.md');
if (process.argv.includes('--check')) {
  const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (now !== out) { console.log('FAIL — docs/wildbond-creatures/catalog.md is out of date: run node tools/wildbond-catalog.cjs'); process.exit(1); }
  console.log(`PASS — creature catalogue current (${ids.length} species).`);
} else {
  fs.writeFileSync(file, out);
  console.log(`Wrote ${path.relative(root, file)}: ${ids.length} species.`);
}
