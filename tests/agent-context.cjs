fs.writeFileSync(path.join(root,'docs/QUEUE.md'),'# Queue\n## This cycle: 2026-10-13 to 2026-10-19\n| Game | ID | Task | Who | Done |\n|---|---|---|---|---|\n| Diamond Manager | DM-1 | First | Codex | Check |\n| | DM-2 | Second | Codex | Check |\n| Wildbond | WB-1 | Other | Claude | Check |\n## Old lane\n| Game | OLD-1 | Stale | Codex | Check |\n');
