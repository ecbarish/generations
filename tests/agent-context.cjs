const {build}=require('../tools/agent-context.cjs'),fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'agent-context-check-')),now=new Date('2026-10-13T12:00:00Z');let checks=0;const check=(fn)=>{fn();checks++;};
